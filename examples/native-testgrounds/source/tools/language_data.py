"""Generate tooltip dictionaries from pinned native translations, not English copies."""

import json
import re
from pathlib import Path

from hwrm_common import CACHE, DONOR, GAME, PROJECT, RUSSIAN_STOCK, save, sha

LANGUAGES = ("English", "French", "German", "Italian", "Spanish", "Russian")


def stock_directory(language):
    if language == "Russian":
        return RUSSIAN_STOCK
    return CACHE / "hwmp-patch-2.4/locales-stock" / language


def verify_native_input(language):
    pins = json.loads((PROJECT / "baseline/native-locale-inputs.json").read_text(encoding="utf8"))
    archive = GAME / "HomeworldRM/Data" / (language + ".big")
    if sha(archive) != pins[language]:
        raise ValueError("Native locale archive changed; review and repin: " + language)
    return archive


def stock_strings(language):
    verify_native_input(language)
    strings = {}
    for path in sorted(stock_directory(language).iterdir()):
        if path.suffix.lower() not in (".ucs", ".dat"):
            continue
        raw = path.read_bytes()
        if raw.startswith((b"\xff\xfe", b"\xfe\xff")):
            text = raw.decode("utf16")
        else:
            try:
                text = raw.decode("utf-8-sig")
            except UnicodeDecodeError:
                text = raw.decode("cp1251" if language == "Russian" else "cp1252")
        for line in text.splitlines():
            row = re.match(r"^(\d+)\s+(.+)$", line)
            if row:
                strings["$" + row[1]] = row[2]
    if len(strings) < 1000:
        raise ValueError("Extract the native language with prepare_inputs.py: " + language)
    return strings


def generate(output, quote):
    from lupa.lua51 import LuaRuntime

    vm = LuaRuntime(register_eval=False, register_builtins=False)
    vm.execute((DONOR / "scripts/productiontimes/localeenglish.lua").read_text(encoding="ascii"))
    english = dict(vm.globals().localization.items())
    labels = json.loads((PROJECT / "localization/hwmp24.json").read_text(encoding="utf8"))
    coverage = {}
    for language in LANGUAGES:
        native = stock_strings(language)
        table = (
            english
            if language == "English"
            else {key: native.get(key, text) for key, text in english.items()}
        )
        fallback = (
            []
            if language == "English"
            else sorted(key for key in english if key not in native and english[key].strip())
        )
        text = "-- Generated by language_data.py; native strings plus explicit English fallback.\n"
        text += (
            "HWMP_TooltipLocalization={\n"
            + "".join(
                "[" + quote(key) + "]=" + quote(value) + ",\n"
                for key, value in sorted(table.items())
            )
            + "}\n"
        )
        for variable, key in (
            ("BaseTime", "base_time"),
            ("Value", "value"),
            ("Seconds", "seconds"),
        ):
            text += "HWMP_Tooltip" + variable + "Label=" + quote(labels[language][key]) + "\n"
        path = output / "locale" / language / "hwmp24_tooltips.lua"
        # Reuse an existing case-insensitive path on Windows.
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="ascii", newline="\n")
        coverage[language] = {
            "dictionary_entries": len(table),
            "native_entries": sum(bool(value.strip()) for value in table.values()) - len(fallback),
            "intentionally_empty_ids": sorted(
                key for key, value in table.items() if not value.strip()
            ),
            "english_fallback_ids": fallback,
            "new_labels": labels[language],
            "native_visual_test": "not_run",
        }
    save(PROJECT / "local/localization-coverage.json", coverage)
    return coverage
